import assert from 'node:assert/strict'
import { compareMriProtocols, groupMriProtocols, parameterSignature, mriValue, decodeMriXml } from '../src/utils/mriProtocols.js'
import { mriWorkbook, mriCsv, mriReportSheets } from '../src/utils/mriProtocolReport.js'

const parameter = (name, values, card = 'Routine') => ({ key: JSON.stringify([card, name]), card, name, values })
const protocol = (id, fileId, parameters, extra = {}) => ({ uid: fileId + ':' + id, id, fileId, fileName: fileId + '.xml', scanner: fileId, name: 't1', region: 'Neuro', exam: 'Head', program: 'Brain', path: 'Neuro/Head/Brain/t1', properties: '', parameters, comparable: parameters.length > 0, issues: [], ...extra })
const a = protocol('same-id', 'A', [parameter('TR', ['525 ms']), parameter('Blank', ['']), parameter('Multi', ['1', '2'])])
const b = protocol('same-id', 'B', [parameter('TR', ['600 ms']), parameter('New', ['0']), parameter('Multi', ['1', '3'])])
const comparison = compareMriProtocols(a, b)
assert.equal(comparison.differences, 4)
assert.deepEqual(comparison.rows.find(r => r.name === 'TR').left, ['525 ms'])
assert.deepEqual(comparison.rows.find(r => r.name === 'TR').right, ['600 ms'])
assert.equal(comparison.rows.find(r => r.name === 'Blank').status, 'only-left')
assert.equal(comparison.rows.find(r => r.name === 'New').status, 'only-right')
assert.equal(mriValue(null), 'No exportado')
assert.equal(mriValue(['']), '(vacío)')
assert.equal(compareMriProtocols(a, { ...a, id: 'different', path: 'elsewhere' }).status, 'same')
assert.equal(compareMriProtocols(a, { ...a, parameters: [...a.parameters].reverse() }).status, 'same')
assert.equal(parameterSignature(a), parameterSignature({ ...a, parameters: [...a.parameters].reverse() }))
assert.equal(compareMriProtocols(a, { ...a, properties: 'TA: 3:00' }).differences, 1)
assert.equal(compareMriProtocols(a, { ...a, comparable: false }).status, 'unknown')
assert.equal(compareMriProtocols(protocol('x', 'A', []), protocol('y', 'B', [])).status, 'unknown')
assert.equal(compareMriProtocols(a, null), null)
assert.equal(compareMriProtocols(protocol('x', 'A', [parameter('TR', ['1 s'])]), protocol('x', 'B', [parameter('TR', ['1000 ms'])])).status, 'different')
const files = [{ id: 'A', fileName: 'A.xml', scanner: 'A', protocols: [a, { ...a, uid: 'A:copy', program: 'Other' }], warnings: [] }, { id: 'B', fileName: 'B.xml', scanner: 'B', protocols: [b], warnings: [] }]
const groups = groupMriProtocols(files)
assert.equal(groups.length, 2)
assert.equal(groups.filter(g => g.common).length, 1)
assert.equal(groups.find(g => g.common).status, 'different')
const duplicates = groupMriProtocols(files, { mode: 'duplicates' })
assert.equal(duplicates.length, 1)
assert.equal(duplicates[0].status, 'same')
assert.equal(groupMriProtocols(files, { match: 'name' }).length, 1)
const upper = [{ ...files[0], protocols: [a] }, { ...files[1], protocols: [{ ...b, name: 'T1' }] }]
assert.equal(groupMriProtocols(upper).length, 1)
assert.equal(groupMriProtocols(upper, { ignoreCase: false }).length, 2)
assert.equal(decodeMriXml(new TextEncoder().encode('<a>ñ</a>')), '<a>ñ</a>')
assert.equal(decodeMriXml(Buffer.from('\uFEFF<a>ñ</a>', 'utf16le')), '<a>ñ</a>')
assert.throws(() => decodeMriXml(Uint8Array.from([255, 255, 255])), /decodificar/)
const sheets = mriReportSheets({ files, groups, mode: 'scanners', match: 'path', ignoreCase: true, left: a, right: b, comparison })
assert.equal(sheets.find(s => s.name === 'Inventario').rows.length, 4)
assert.equal(sheets.find(s => s.name === 'Comparación').rows.length, 5)
const workbook = await mriWorkbook([{ name: 'Datos', rows: [['Name', 'Value'], ['=1+1', '<xml>&_x000A_']] }]).arrayBuffer()
const bytes = Buffer.from(workbook)
assert.equal(bytes.readUInt32LE(0), 0x04034b50)
assert.equal(bytes.readUInt32LE(bytes.length - 22), 0x06054b50)
const content = bytes.toString('utf8')
assert.match(content, /t="inlineStr"/)
assert.match(content, /&lt;xml&gt;&amp;_x005F_x000A_/)
assert.ok(!content.includes('<f>'))
assert.throws(() => mriWorkbook([{ name: 'Data', rows: [['x'.repeat(32768)]] }]), /máximo/)
const csv = mriCsv([['=1+1', ' @SUM(A1)', 'a;"b', 'line1\nline2']])
assert.ok(csv.startsWith('\uFEFF'))
assert.ok(csv.includes('"\'=1+1"'))
assert.ok(csv.includes('"\' @SUM(A1)"'))
assert.ok(csv.includes('"a;""b"'))
console.log('MRI core: comparison direction, missing vs empty, repeated values, incomplete data, grouping, encoding and safe exports passed.')
