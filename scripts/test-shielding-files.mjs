import assert from 'node:assert/strict'
import { checkPlanFile, boundedRasterSize, imageHeaderSize } from '../src/utils/shieldingFiles.js'
const file = (name, type, size = 512) => ({ name, type, size })
assert.equal(checkPlanFile(file('plano.PDF', 'application/pdf')), 'pdf')
assert.equal(checkPlanFile(file('plano.png', 'image/png')), 'image')
assert.equal(checkPlanFile(file('plano.jpg', 'image/jpeg')), 'image')
assert.throws(() => checkPlanFile(file('script.svg', 'image/svg+xml')))
assert.throws(() => checkPlanFile(file('plano.png', 'text/html')))
assert.throws(() => checkPlanFile(file('plano.pdf', 'application/pdf', 0)))
assert.throws(() => checkPlanFile(file('plano.png', 'image/png', 30 * 1024 * 1024)))
assert.deepEqual(boundedRasterSize(100, 50), { width: 100, height: 50 })
const size = boundedRasterSize(10000, 5000)
assert.equal(size.width / size.height, 2)
assert.ok(size.width <= 4096 && size.width * size.height <= 12000000)
assert.throws(() => boundedRasterSize(0, 1))
// Header-only fixtures are synthetic, not uploaded clinical plans.
const png = new Uint8Array(24), pngView = new DataView(png.buffer)
pngView.setUint32(0, 0x89504e47); pngView.setUint32(4, 0x0d0a1a0a)
pngView.setUint32(16, 320); pngView.setUint32(20, 240)
assert.deepEqual(imageHeaderSize(png), { width: 320, height: 240 })
const jpeg = new Uint8Array([0xff, 0xd8, 0xff, 0xc0, 0, 11, 8, 0, 240, 1, 64, 1, 1, 0x11, 0])
assert.deepEqual(imageHeaderSize(jpeg), { width: 320, height: 240 })
assert.throws(() => imageHeaderSize(new Uint8Array([1, 2, 3])))
assert.throws(() => imageHeaderSize(jpeg.slice(0, 8)))
console.log('Shielding files: format, size and raster bounds pass.')
